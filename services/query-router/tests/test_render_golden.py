def _assert_self_parses(sql: str, dialect: str) -> None:
    """Self-parse invariant: rendered SQL must re-parse in its own dialect."""
    parsed = sqlglot.parse_one(sql, read=dialect)
    assert parsed is not None, f"Rendered SQL parsed to None ({dialect}): {sql}"


def _check_golden(name: str, actual: str) -> None:
    GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
    path = GOLDEN_DIR / f"{name}.sql"
    if os.environ.get("UPDATE_GOLDENS"):
        path.write_text(actual + "\n", encoding="utf-8")
        return
    assert path.exists(), (
        f"Missing golden {path.name}. Re-run with UPDATE_GOLDENS=1 to create it."
    )
    expected = path.read_text(encoding="utf-8").rstrip("\n")
    assert actual == expected, (
        f"Golden mismatch for {name}.\n"
        f"  expected: {expected}\n"
        f"  actual:   {actual}\n"
        f"If this change is intentional, re-run with UPDATE_GOLDENS=1."
    )


def _common_assertions(sql: str, shape: str, dialect: str) -> None:
    assert isinstance(sql, str) and sql.strip()
    # Finding-1 negative invariant: the literal "(None)" must never leak.
    assert "(None)" not in sql, f"Literal (None) leaked into {shape}/{dialect}: {sql}"
    _assert_self_parses(sql, dialect)
    _check_golden(f"{shape}__{dialect}", sql)


