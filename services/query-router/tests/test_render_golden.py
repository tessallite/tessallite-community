def _agg_col(measure_name, stat_type):
    return types.SimpleNamespace(
        physical_col_name=f"{measure_name}__{stat_type}",
        stat_type=stat_type,
        measure=types.SimpleNamespace(name=measure_name) if measure_name else None,
    )


def _aggregate(grain, columns):
    return types.SimpleNamespace(
        id="agg-golden", grain=list(grain), columns=list(columns),
        status="active", physical_table_name="agg_golden",
        target_schema="aggregates", persona_id=None,
    )


def _agg_bind(sql, measures, dimensions, *, filters=None):
    lq = parse_sql_to_ir(sql, MODEL_ID)
    model = types.SimpleNamespace(
        id=MODEL_ID, slug=MODEL_SLUG, status="active",
        aggregations_enabled=True,
    )
    return BoundQuery(
        logical_query=lq, model=model, resolved_measures=measures,
        resolved_dimensions=dimensions, resolved_filters=filters or [],
        resolved_dimensions_by_name={d.name: d for d in dimensions},
    )


