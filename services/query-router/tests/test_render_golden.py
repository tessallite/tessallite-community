def _tbl(id_, physical_name, alias, table_type="fact"):
    return types.SimpleNamespace(
        id=id_, model_id=MODEL_ID, physical_name=physical_name,
        alias=alias, table_type=table_type, source_id="src-1",
    )


def _col(id_, table_id, column_name, data_type="text"):
    return types.SimpleNamespace(
        id=id_, model_table_id=table_id, column_name=column_name,
        data_type=data_type,
    )


def _dim(name, *, source_column_id=None, user_defined_attribute_id=None,
         is_time_dim=False):
    return types.SimpleNamespace(
        id=f"d-{name}", model_id=MODEL_ID, name=name,
        source_column_id=source_column_id,
        user_defined_attribute_id=user_defined_attribute_id,
        calc_expression=None, is_time_dim=is_time_dim, time_grain=None,
    )


def _meas(name, *, default_agg="sum", source_column_id=None,
          user_defined_attribute_id=None, measure_type="standard"):
    return types.SimpleNamespace(
        id=f"m-{name}", model_id=MODEL_ID, name=name,
        default_agg=default_agg, is_additive=True,
        measure_type=measure_type, source_column_id=source_column_id,
        user_defined_attribute_id=user_defined_attribute_id,
        expression=None, calc_agg_mode=None, variant_kind=None,
        variant_of_measure_id=None, variant_n=None,
        semi_additive_behavior=None,
    )


def _uda(id_, name, table_id, expression, *, output_data_type=None,
         validated=True, validation_error=None):
    return types.SimpleNamespace(
        id=id_, model_id=MODEL_ID, name=name, table_id=table_id,
        expression=expression, validated=validated,
        validation_error=validation_error, output_data_type=output_data_type,
    )


def _se(raw_text, *, classification, alias=None, agg_function=None,
        inner_column=None, inner_literal=None):
    return SelectExpression(
        raw_text=raw_text, alias=alias, classification=classification,
        agg_function=agg_function, inner_column=inner_column,
        inner_literal=inner_literal,
    )


def _bound(*, measures, dimensions=None, filters=None, grain=None,
           order_by=None, limit=None, offset=None, raw_query="SELECT 1",
           select_expressions=None, input_dialect="postgres",
           from_tables=None, has_passthrough_expressions=False,
           has_distinct=False, having_raw=None, select_star=False,
           has_unresolvable_order=False):
    dims = dimensions or []
    model = types.SimpleNamespace(
        id=MODEL_ID, slug=MODEL_SLUG, display_name="golden",
        deployed_version_id="v1",
    )
    lq = LogicalQuery(
        model_id=MODEL_ID, protocol="jdbc", raw_query=raw_query,
        requested_measures=[m.name for m in measures],
        requested_dimensions=[d.name for d in dims],
        filters=filters or [],
        grain=grain if grain is not None else [d.name for d in dims],
        order_by=order_by or [], limit=limit, offset=offset,
        query_fingerprint="fp-golden",
        select_expressions=select_expressions or [],
        from_tables=from_tables or [],
        input_dialect=input_dialect,
        has_distinct=has_distinct,
        having_raw=having_raw,
        select_star=select_star,
        has_unresolvable_order=has_unresolvable_order,
    )
    return BoundQuery(
        logical_query=lq, model=model, resolved_measures=measures,
        resolved_dimensions=dims, resolved_filters=filters or [],
        resolved_dimensions_by_name={d.name: d for d in dims},
        has_passthrough_expressions=has_passthrough_expressions,
    )


def _fact_db(*, dimensions=(), measures=(), udas=()):
    fact = _tbl("t-fact", "demo.sales", "f")
    cols = [
        _col("c-region", "t-fact", "region"),
        _col("c-amount", "t-fact", "amount", data_type="numeric"),
        _col("c-qty", "t-fact", "qty", data_type="integer"),
    ]
    return FakeDB(tables=[fact], columns=cols, measures=list(measures),
                  dimensions=list(dimensions), udas=list(udas))


def _join_db(*, dimensions=(), measures=(),
             fact_key="country_id", fact_key_type="integer",
             dim_key="id", dim_key_type="integer"):
    """Fact (demo.sales / alias 'f') joined to a dimension table
    (demo.country / alias 'd') on ``fact_key = dim_key``.  Varying the key
    data types drives the DATE/TIMESTAMP join-coercion path (#34)."""
    fact = _tbl("t-fact", "demo.sales", "f", table_type="fact")
    dimt = _tbl("t-dim", "demo.country", "d", table_type="dimension")
    cols = [
        _col("c-region", "t-fact", "region"),
        _col("c-amount", "t-fact", "amount", data_type="numeric"),
        _col("c-qty", "t-fact", "qty", data_type="integer"),
        _col("c-fkey", "t-fact", fact_key, data_type=fact_key_type),
        _col("c-dkey", "t-dim", dim_key, data_type=dim_key_type),
        _col("c-cname", "t-dim", "country_name"),
        _col("c-fperiod", "t-dim", "fiscal_period"),
    ]
    join = types.SimpleNamespace(
        id="j-1", model_id=MODEL_ID,
        left_table_id="t-fact", left_column_id="c-fkey",
        right_table_id="t-dim", right_column_id="c-dkey",
        join_type="inner",
    )
    return FakeDB(tables=[fact, dimt], columns=cols, joins=[join],
                  measures=list(measures), dimensions=list(dimensions))


