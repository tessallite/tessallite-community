# Bug-1605 — persona-narrowed SELECT * with an EXPRESSION ORDER BY + LIMIT.
#
# ``_build_persona_star_sql`` previously dropped the unresolvable ORDER BY but
# kept the LIMIT unconditionally — returning an ARBITRARY top-N (a silent wrong
# result). The round-2 fix reconstructs the raw ORDER BY over the persona-allowed
# physical columns when EVERY referenced column is allowed (correct top-N), and
# otherwise suppresses the LIMIT so the result is never a silently-wrong top-N
# and never leaks a non-visible column.
