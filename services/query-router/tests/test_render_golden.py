"""Phase 1 — deterministic, offline golden-SQL render harness (all 30 shapes).

Renders ``BoundQuery -> SQL`` for every shape in
``architecture_query-shape-catalog.md``, parametrized across the four target
dialects (postgres / bigquery / spark / tsql) where the producing path emits
dialect-translated SQL.  Two guarantees are enforced on every render:

1. **Self-parse invariant** — the rendered SQL is re-parsed in its own target
   dialect.  Any unparseable emission fails the test.  This structurally
   catches the Finding-1 class (literal ``(None)`` and similar malformed
   output) going forward, regardless of which code path produced it.
2. **Golden snapshot** — the rendered SQL is pinned to a file under
   ``tests/golden/render/``.  This is the refactor lock for Phase 3: any
   change in emitted SQL must be reviewed and re-pinned deliberately.

Goldens are regenerated by running with ``UPDATE_GOLDENS=1`` in the env.

Three offline-driveable producing paths are exercised:

* **source** — ``rewrite_for_source`` -> ``_build_source_sql``.  PostgreSQL is
  built logically then transpiled once at the boundary, so these render for
  ALL four dialects.
* **passthrough / SELECT *** — ``rewrite_for_source`` ->
  ``_substitute_table_names``.  This path does regex table substitution and
  preserves the input (PostgreSQL-canonical) SQL verbatim, then applies
  ``_requote_identifiers_for_dialect`` for all non-postgres targets.  Complex
  passthrough is pinned for ``postgres`` only (and SELECT * for ``postgres``
  + ``bigquery``); remaining cross-dialect passthrough expansions are tracked
  in the catalog G-series.
* **aggregate** — ``rewrite_for_aggregate`` against a pre-materialised
  aggregate definition.  Rendered for all four dialects.

Shapes that route through a *different* subsystem with its own dedicated test
suite (security wrap, pocket matcher, DAX translator, multi-source) are NOT
golden-rendered here; they are enumerated in :data:`SHAPE_COVERAGE` with their
owning suite, and :func:`test_all_30_shapes_accounted_for` asserts the full
1..30 set is covered so nothing is silently descoped.

The FakeDB scaffold mirrors the proven pattern in ``test_calculated_rewrite.py``
(dispatches ``select(Model)`` to pre-seeded row lists, supports ``db.get``).
"""
