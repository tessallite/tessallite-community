def _persona_bound(*, dimensions, measures, raw_query, limit=None, offset=None):
    """Build a persona-narrowed ``SELECT *`` BoundQuery flagged
    ``has_unresolvable_order`` (an expression sort the parser could not
    represent as a bare column)."""
    bq = _bound(
        measures=list(measures), dimensions=list(dimensions),
        grain=[],
        order_by=[], has_unresolvable_order=True,
        limit=limit, offset=offset,
        select_star=True,
        raw_query=raw_query,
    )
    bq.persona_narrowed_star = True
    return bq


