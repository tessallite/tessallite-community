# ---------------------------------------------------------------------------
# Bug-4467 (AKA Bug-809): a persona/CLS-narrowed SELECT * with a WHERE / GROUP
# BY / ORDER BY on a JOINED-DIMENSION column previously fell back to a raw
# SELECT * via _substitute_table_names — which READS every physical column from
# the source (including the hidden/restricted ones the narrowing removed). The
# fix emits an EXPLICIT allowed-column projection spanning the base + joined
# relations, and rejects (403) when a clause references a non-allowed column.
# ---------------------------------------------------------------------------


def _persona_star_join_db():
    """Fact ``demo.sales`` (alias 'f') joined to dim ``demo.country`` (alias
    'd') on ``country_id = id``. The fact carries a HIDDEN ``secret_code``
    column that the persona narrowing removed — it must NEVER appear in the
    rendered SQL."""
    fact = _tbl("t-fact", "demo.sales", "f", table_type="fact")
    dimt = _tbl("t-dim", "demo.country", "d", table_type="dimension")
    cols = [
        _col("c-region", "t-fact", "region"),
        _col("c-amount", "t-fact", "amount", data_type="numeric"),
        _col("c-secret", "t-fact", "secret_code"),          # hidden / restricted
        _col("c-fkey", "t-fact", "country_id", data_type="integer"),
        _col("c-dkey", "t-dim", "id", data_type="integer"),
        _col("c-cname", "t-dim", "country_name"),
    ]
    join = types.SimpleNamespace(
        id="j-1", model_id=MODEL_ID,
        left_table_id="t-fact", left_column_id="c-fkey",
        right_table_id="t-dim", right_column_id="c-dkey",
        join_type="inner",
    )
    return FakeDB(tables=[fact, dimt], columns=cols, joins=[join])


def _persona_star_bound(*, dimensions, measures, raw_query, grain=None,
                        filters=None, order_by=None, limit=None,
                        has_unresolvable_order=False):
    bq = _bound(
        measures=list(measures), dimensions=list(dimensions),
        grain=grain if grain is not None else [],
        filters=filters or [], order_by=order_by or [],
        limit=limit, select_star=True, raw_query=raw_query,
        has_unresolvable_order=has_unresolvable_order,
    )
    bq.persona_narrowed_star = True
    return bq


