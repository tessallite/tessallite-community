@router.patch("/config", response_model=AgentConfigResponse)
async def patch_agent_config(
    project_id: UUID,
    body: AgentConfigPatch,
    current_user: CurrentUser = Depends(forbid_embed_user),
) -> AgentConfigResponse:
    await _require_project_modeller(project_id, current_user)
    async for db in get_tenant_db(current_user.tenant_id):
        result = await db.execute(
            select(ProjectAgentConfig).where(
                ProjectAgentConfig.project_id == project_id
            )
        )
        record = result.scalar_one_or_none()
        if record is None:
            raise HTTPException(status_code=404, detail="Agent not configured")
        for k, v in body.model_dump(exclude_unset=True).items():
            setattr(record, k, v)
        if getattr(record, "enabled", False):
            count_result = await db.execute(
                select(ProjectAgentModel).where(
                    ProjectAgentModel.project_id == project_id
                )
            )
            allow_count = len(count_result.scalars().all())
            full_body = AgentConfigResponse.model_validate(record)
            _validate_for_enable(full_body, allow_count)
        await db.commit()
        await db.refresh(record)
        return AgentConfigResponse.model_validate(record)
    raise HTTPException(status_code=500, detail="DB session exhausted")


@router.put(
    "/config",
    response_model=AgentConfigResponse,
    summary="Create or fully replace the project agent config",
    description=(
        "**Full-replace contract (Bug-1029).** This is a true HTTP PUT: the "
        "request body is the complete desired state of the agent config. "
        "Every field omitted from the body is reset to its schema default — "
        "including `enabled` (defaults to `false`, which disables the agent) "
        "and the LLM-config bindings (`answer_llm_config_id` etc., default "
        "`null`). Send the entire object, not a delta.\n\n"
        "For partial updates that touch only specific fields, use "
        "`PATCH /config`, which merges with `exclude_unset` semantics and is "
        "what the SPA uses. A partial PUT will silently clobber omitted "
        "fields."
    ),
)
async def upsert_agent_config(
    project_id: UUID,
    body: AgentConfigUpsert,
    current_user: CurrentUser = Depends(forbid_embed_user),
) -> AgentConfigResponse:
    """Create or fully replace the agent config (PUT = replace, not merge).

    Bug-1029 — `body.model_dump()` is applied without `exclude_unset`, so
    every field absent from the request reverts to its default. This is the
    intended PUT semantics (replace the whole resource); the contract is
    documented on the route above and partial callers must use PATCH.
    """
    await _require_project_modeller(project_id, current_user)
    async for db in get_tenant_db(current_user.tenant_id):
        proj = await db.get(Project, project_id)
        if proj is None:
            raise HTTPException(status_code=404, detail="Project not found")

        result = await db.execute(
            select(ProjectAgentConfig).where(
                ProjectAgentConfig.project_id == project_id
            )
        )
        record = result.scalar_one_or_none()

        count_result = await db.execute(
            select(ProjectAgentModel).where(
                ProjectAgentModel.project_id == project_id
            )
        )
        allow_count = len(count_result.scalars().all())
        _validate_for_enable(body, allow_count)

        first_creation = record is None
        if record is None:
            record = ProjectAgentConfig(project_id=project_id)
            db.add(record)

        incoming = body.model_dump()
        if first_creation:
            for field, default_val in _TEMPLATE_DEFAULTS.items():
                client_val = incoming.get(field)
                if client_val is None or (isinstance(client_val, str) and not client_val.strip()):
                    incoming[field] = default_val

        for k, v in incoming.items():
            setattr(record, k, v)

        if first_creation and incoming.get("judge_rubric_id") is None:
            rubric = AgentJudgeRubric(
                project_id=project_id,
                name="Standard Quality",
                sections=_DEFAULT_RUBRIC_SECTIONS,
            )
            db.add(rubric)
            await db.flush()
            record.judge_rubric_id = rubric.id

        await db.commit()
        await db.refresh(record)
        return AgentConfigResponse.model_validate(record)
    raise HTTPException(status_code=500, detail="DB session exhausted")


