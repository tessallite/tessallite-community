class SelectableModel(BaseModel):
    """A model the end user may pin to a conversation (id + display name)."""
    id: UUID
    name: str


@router.get("/selectable-models", response_model=list[SelectableModel])
async def list_selectable_models(
    project_id: UUID,
    current_user: CurrentUser = Depends(require_capability("chat")),
) -> list[SelectableModel]:
    """Models a chat caller may pin to a conversation: the project agent
    allow-list, further narrowed to the embed token's persona scope when
    present. Reachable by embed users (unlike GET /models) because it drives the
    in-chat model picker. Uses the same scoping helpers as prompt assembly so
    the picker can only ever offer what the agent would actually accept."""
    # Embed tokens may be restricted to a subset of projects.
    if isinstance(current_user, CurrentEmbedUser):
        if (
            current_user.project_ids is not None
            and str(project_id).lower() not in current_user.project_ids
        ):
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Embed token does not grant access to this project",
            )

    # Imported lazily to avoid a circular import at module load (assembler pulls
    # in pipeline-adjacent modules).
    from src.prompt.assembler import (
        _apply_persona_filter,
        _load_model_profiles,
        _load_persona_scopes,
    )

    async for db in get_tenant_db(current_user.tenant_id):
        allow_q = await db.execute(
            select(ProjectAgentModel.model_id).where(
                ProjectAgentModel.project_id == project_id
            )
        )
        allow_ids = [row for row in allow_q.scalars().all()]
        profiles = await _load_model_profiles(db, project_id, allow_ids)

        persona_id = None
        if isinstance(current_user, CurrentEmbedUser) and current_user.persona_id:
            persona_id = UUID(current_user.persona_id)
        if persona_id is not None:
            persona_scopes = await _load_persona_scopes(db, persona_id)
            profiles = _apply_persona_filter(profiles, persona_scopes)

        return [SelectableModel(id=p.id, name=p.display_name) for p in profiles]
    raise HTTPException(status_code=500, detail="DB session exhausted")


@router.put("/models")
async def replace_allow_list(
    project_id: UUID,
    body: AllowListReplace,
    current_user: CurrentUser = Depends(forbid_embed_user),
) -> list[UUID]:
    await _require_project_modeller(project_id, current_user)
    async for db in get_tenant_db(current_user.tenant_id):
        # Validate every model belongs to this project.
        for mid in body.model_ids:
            m = await db.get(Model, mid)
            if m is None or m.project_id != project_id:
                raise HTTPException(
                    status_code=400,
                    detail=f"Model {mid} not in project {project_id}",
                )
        # Replace allow-list atomically.
        existing = await db.execute(
            select(ProjectAgentModel).where(
                ProjectAgentModel.project_id == project_id
            )
        )
        for row in existing.scalars().all():
            await db.delete(row)
        for mid in body.model_ids:
            db.add(ProjectAgentModel(project_id=project_id, model_id=mid))
        await db.commit()
        return list(body.model_ids)
    raise HTTPException(status_code=500, detail="DB session exhausted")


