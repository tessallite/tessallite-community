def _validate_for_enable(body: AgentConfigUpsert, allow_list_count: int) -> None:
    """Enabling requires an LLM config and at least one allow-listed model."""
    if not body.enabled:
        return
    missing = []
    if body.answer_llm_config_id is None:
        missing.append("answer_llm_config_id")
    if allow_list_count < 1:
        missing.append("model_ids")
    if missing:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Cannot enable agent: missing fields {missing}",
        )


